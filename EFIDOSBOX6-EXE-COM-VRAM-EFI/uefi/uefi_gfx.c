void draw_charbasic(int x, int y, char c, UINT32 color) {
    uint8_t uc = (uint8_t)c;  // <-- MUY IMPORTANTE

    for (int row = 0; row < 8; row++) {
        uint8_t bits = font8x8_basic[uc][row];

        for (int col = 0; col < 8; col++) {
            if (bits & (1 << (7 - col))) {
                gfx_fb[(y + row) * gfx_pitch + (x + col)] = color;
            }
        }
    }
}
